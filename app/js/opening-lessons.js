// ply / at — количество уже сыгранных полуходов от начала партии.
const note = (ply, title, text, arrows = '') => ({
  ply, title, text,
  arrows: arrows.split(' ').filter(Boolean).map((pair) => ({
    from: pair.slice(0, 2), to: pair.slice(2, 4),
  })),
});
const branch = (at, title, moves, why) => ({
  at, title, moves: moves.split(' '), why,
});
const chapter = (id, title, summary, moves, notes, branches = []) => ({
  id, title, summary, moves: moves.split(' '),
  notes: Object.fromEntries(notes.map((entry) => [entry.ply, entry])),
  branches,
});

