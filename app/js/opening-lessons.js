export function courseByName(name, side) {
  return OPENING_COURSES.find((course) => course.title === name && course.side === side) || null;
}

export function makeOpeningPosition(moves, ply, ChessType) {
  const game = new ChessType();
  let lastMove = null;
  for (const san of moves.slice(0, ply)) {
    const result = game.move(san);
    if (!result) throw new Error('Некорректная учебная последовательность: ' + san);
    lastMove = result;
  }
  return { game, lastMove };
}
