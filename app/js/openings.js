export const OPENING_LINES = LINES.map(([name, moves]) => ({ name, moves: moves.split(' ') }));

// sans — ходы партии (SAN). Возвращает { bookPlies, name }:
// bookPlies — сколько первых полуходов совпадают с книгой; name — самое подробное подходящее название.
export function openingInfo(sans) {
  let bookPlies = 0;
  let name = null, nameLen = 0;
  for (const line of OPENING_LINES) {
    let k = 0;
    while (k < line.moves.length && k < sans.length && line.moves[k] === sans[k]) k++;
    if (k > bookPlies) bookPlies = k;
    if (k === line.moves.length && k >= nameLen) { name = line.name; nameLen = k; }
  }
  return { bookPlies, name };
}
